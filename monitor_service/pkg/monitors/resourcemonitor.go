type EventHandler func(event *monitoring.MonitoringEvent) error

type ResourceMonitor struct {
	obs *observability.Client
	ctx context.Context

	target     *monitoring.ResourceKey
	meters     map[string]meters.Meter
	collectors []collectors.Collector

	eventHandler EventHandler

	running bool
	stopCh  chan struct{}

	mu sync.Mutex
}

// scheduleGroup represents one ticker: collectors and metrics
// with the same interval share one ticker to reduce goroutine overhead.
type scheduleGroup struct {
	interval time.Duration
	ticker   *time.Ticker

	collectors []collectors.Collector
	metricIDs  []string
}

func NewResourceMonitor(
	target *monitoring.ResourceKey,
	eventHandler EventHandler, // a callbak function to handle events generated by the monitor
	obs *observability.Client,
) *ResourceMonitor {
	return &ResourceMonitor{
		target:       target,
		meters:       make(map[string]meters.Meter),
		eventHandler: eventHandler,
		obs:          obs,
		ctx:          context.Background(),
	}
}

func (m *ResourceMonitor) Resource() *monitoring.ResourceKey {
	return m.target
}

// Start starts the background monitoring scheduler.
func (m *ResourceMonitor) Start() error {

	m.mu.Lock()

	if m.running {
		m.mu.Unlock()
		return fmt.Errorf("monitor is already running")
	}

	m.running = true
	m.stopCh = make(chan struct{})

	stopCh := m.stopCh

	// Copy collectors/meters configuration before starting the scheduler.
	collectorsSnapshot := append([]collectors.Collector(nil), m.collectors...)
	metersSnapshot := copyMeters(m.meters)

	m.mu.Unlock()

	// Build the schedule from the snapshot.
	schedule, err := buildSchedule(collectorsSnapshot, metersSnapshot)
	if err != nil {
		m.Stop()
		return err
	}
	fmt.Println("=== Schedule ===")
	fmt.Println("Target monitor: ", m.target.String())
	fmt.Println("===============")
	for i, group := range schedule {
		fmt.Printf("Group %d\n", i+1)
		fmt.Printf("  Interval: %s\n", group.interval)
		fmt.Printf("  Collectors: [")

		for i, collector := range group.collectors {
			if i > 0 {
				fmt.Printf(",")
			}
			fmt.Printf("[")
			for j, counterID := range collector.CounterIds() {
				if j > 0 {
					fmt.Printf(",")
				}
				fmt.Printf("%q", counterID)
			}
			fmt.Printf("]")
		}

		fmt.Printf("]\n")
		fmt.Printf("  Metrics:  %v\n", group.metricIDs)
		fmt.Printf("  Ticker:   %v\n", group.ticker != nil)
		fmt.Println()
	}
	fmt.Println("===============")

	go m.runLoop(stopCh, schedule)

	return nil
}

// Stop stops the background monitoring scheduler.
func (m *ResourceMonitor) Stop() {
	m.mu.Lock()
	defer m.mu.Unlock()

	if !m.running {
		return
	}

	m.running = false

	close(m.stopCh)
	m.stopCh = nil
}

// AddCollector registers a collector used by this monitor.
func (m *ResourceMonitor) AddCollector(counter *monitoring.Counter, resource *monitoring.ResourceKey, session *netconf.Session, catalog *catalog.Catalog) error {

	if counter == nil {
		return fmt.Errorf("counter is nil")
	}

	if resource.NodeId != m.target.NodeId {
		return fmt.Errorf("counter doesn't belong to the assigned monitor, target node ID is not matching")
	}

	for _, collector := range m.collectors {
		if collector.PollInterval() == counter.PollIntervalMs && collector.Target() == m.target {
			if collector.HasCounter(counter.Name) {
				return nil // Collector already registered for this counter and interval.
			} else {
				if err := collector.AddCounter(counter); err != nil {
					return fmt.Errorf("failed to add counter %q to collector: %w", counter.Name, err)
				}
				return nil // Add the counter to the existing collector with the same interval.
			}
		}
	}
	// No existing collector with the same interval, create a new one.
	newCollector := collectors.NewNetconfCollector(
		resource,
		session,
		catalog,
		m.obs,
		counter.PollIntervalMs,
	)

	if err := newCollector.AddCounter(counter); err != nil {
		return fmt.Errorf("failed to add counter %q to new collector: %w", counter.Name, err)
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	if m.running {
		return fmt.Errorf(
			"cannot add collector while monitor is running",
		)
	}

	m.collectors = append(
		m.collectors,
		newCollector,
	)

	return nil
}

// AddMeter registers a meter used by this monitor.
func (m *ResourceMonitor) AddMeter(metric *monitoring.Metric, resource *monitoring.ResourceKey) error {

	if metric == nil {
		return fmt.Errorf("metric is nil")
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	if meter, exists := m.meters[metric.Name]; exists {
		meter.Metric().EvaluationIntervalMs = metric.EvaluationIntervalMs
		return nil // Meter already registered, update the evaluation interval.
	}

	meter, err := meters.NewPacketRateMeter(resource, m.obs, metric)
	if err != nil {
		return fmt.Errorf("failed to create meter for metric %q: %w", metric.Name, err)
	}

	if m.running {
		return fmt.Errorf(
			"cannot add meter while monitor is running",
		)
	}

	m.meters[metric.Name] = meter
	return nil
}

// runLoop owns the single scheduler goroutine.
//
// There may be multiple tickers, but there is only ONE goroutine
// consuming them.
//
// For every tick:
//
//  1. Collect due collectors.
//  2. Measure due metrics.
//
// Therefore, even when collection and measurement have different
// intervals, collection is always processed before measurement
// when both are due at the same time.
func (m *ResourceMonitor) runLoop(stopCh <-chan struct{}, schedule []*scheduleGroup) {
	defer stopSchedule(schedule)

	cases := make([]reflectSelectCase, 0, len(schedule)+1)

	// Case 0 is always the stop channel.
	cases = append(cases, reflectSelectCase{stopCh: stopCh})

	for _, group := range schedule {
		cases = append(cases, reflectSelectCase{tickerCh: group.ticker.C, group: group})
	}

	for {
		index := selectSchedule(cases)

		// Stop requested.
		if index == 0 {
			return
		}

		group := cases[index].group

		if group == nil {
			continue
		}

		// ----------------------------------------------------
		// 1. COLLECTION
		// ----------------------------------------------------

		if len(group.collectors) > 0 {
			if err := m.collectAndFeed(group.collectors); err != nil {
				// TODO: log/report monitor error with obesrvability package.
				continue
			}
		}

		// ----------------------------------------------------
		// 2. MEASUREMENT
		// ----------------------------------------------------

		if len(group.metricIDs) > 0 {
			if err := m.measureAndFeed(group.metricIDs); err != nil {
				// TODO: log/report monitor error.
				continue
			}
		}
	}
}

